COACH_MODE = "coach"
COACH_DISCLOSURE = (
    "I'm an AI coach. I explain your numbers and run what-if checks; every number comes from a calculation engine, not from the "
    "AI model. I'm not a human adviser and I don't give regulated investment advice. Projections are not guarantees."
)
HUMAN_REQUEST = re.compile(
    r"\b(talk|speak|chat) to (a |an )?(human|person|adviser|advisor|someone)\b|\breal (person|human)\b|\bhuman (adviser|advisor|agent)\b",
    re.I,
)
HUMAN_REPLY = (
    "Of course. I've asked a person on our team to follow up with you. You can see the request under Settings → Support."
)
# What an LLM-polished reply must not contain even when its numbers are grounded: product pushes and promises.
MAX_REPLY_CHARS = 1500


@dataclass
class CoachTurn:
    message_id: uuid.UUID
    assistant_text: str
    mode: str
    tools: list[str]
    advice_class: str
    escalation_suggested: bool = False
    escalation_id: uuid.UUID | None = None
    llm_used: bool = False
    grounded: bool = True
    suggestions: list[str] = field(default_factory=list)


def _now() -> datetime:
    return datetime.now(UTC)


class CoachService:
    def __init__(self, session: AsyncSession, settings: Settings, provider: LLMProvider | None) -> None:
        self.s, self.cfg, self.provider = session, settings, provider

    async def _conv(self, user_id: uuid.UUID, conv_id: uuid.UUID) -> Conversation:
        c = await self.s.get(Conversation, conv_id)
        if c is None or c.user_id != user_id or c.mode != COACH_MODE:  # never reveal other users' conversations
            raise AppError(404, "not_found", "Conversation not found")
        return c

    async def _add(self, conv_id: uuid.UUID, role: str, content: str, advice_class: str | None = None) -> Message:
        m = Message(
            id=uuid.uuid4(), conversation_id=conv_id, role=role, content=content, advice_class=advice_class, created_at=_now()
        )
        self.s.add(m)
        await self.s.flush()
        return m

    async def start(self, user_id: uuid.UUID) -> tuple[Conversation, Message]:
        if await active_consent(self.s, user_id, "ai_processing") is None:
            raise AppError(403, "consent_required", "AI processing consent is required",
                           "Please agree to AI processing of what you tell me before we start.")  # fmt: skip
        conv = Conversation(id=uuid.uuid4(), user_id=user_id, mode=COACH_MODE, intents=[])
        self.s.add(conv)
        await self.s.flush()
        first = await self._add(
            conv.id, "assistant", f"Hi, I'm your coach. {CAPABILITIES} What would you like to look at?", "information"
        )
        await audit(self.s, action="coach.started", entity_type="conversation", entity_id=str(conv.id), actor_user_id=user_id)
        return conv, first

    async def transcript(self, user_id: uuid.UUID, conv_id: uuid.UUID) -> list[Message]:
        await self._conv(user_id, conv_id)
        q = select(Message).where(Message.conversation_id == conv_id).order_by(Message.created_at)
        return list((await self.s.execute(q)).scalars().all())

    async def suggested_prompts(self, user_id: uuid.UUID) -> list[str]:
        """State-aware starter questions. Static text only; nothing here is generated by a model."""
        out: list[str] = []
        if await ScoringService(self.s, self.cfg).latest(user_id) is not None:
            out += [
                "Explain my score",
                "What is holding my score back?",
                "Why did my score change?",
                "What are the wealth stages?",
            ]
        else:
            out.append("What information do you still need from me?")
        out.append("What have you saved about me?")
        if await GoalService(self.s).list(user_id):
            out.append("Is my goal on track assuming 8% return and 6% inflation?")
        return out

    async def _run_tool(self, tools: CoachTools, name: str, text: str) -> ToolResult:
        match name:
            case "get_score":
                return await tools.get_score()
            case "explain_score":
                return await tools.explain_score()
            case "score_change":
                return await tools.score_change()
            case "stage_info":
                return await tools.stage_info()
            case "profile_summary":
                return await tools.profile_summary()
            case "missing_data":
                return await tools.missing_data()
            case "goals_overview":
                return await tools.goals_overview()
            case "goal_status":
                return await tools.goal_status(text)
            case "act":
                return tools.action_unavailable()
        raise AppError(500, "internal_error", "Unknown coach tool")

    async def _finish(self, conv: Conversation, user_id: uuid.UUID, reply: str, advice: str, mode: str, tools: list[str], *,
                      llm_used: bool = False, prompt_version: str | None = None, grounded: bool = True, fallback: str | None = None,
                      escalation_suggested: bool = False, escalation_id: uuid.UUID | None = None, request_id: str | None = None) -> CoachTurn:  # fmt: skip
        am = await self._add(conv.id, "assistant", reply, advice)
        self.s.add(CoachRun(id=uuid.uuid4(), conversation_id=conv.id, message_id=am.id, mode=mode, tools=tools, llm_used=llm_used,
                            prompt_version=prompt_version, grounded=grounded, fallback_reason=fallback,
                            rulebook_version=DEFAULT_VERSION, created_at=_now()))  # fmt: skip
        await audit(self.s, action="coach.turn", entity_type="conversation", entity_id=str(conv.id), actor_user_id=user_id,
                    request_id=request_id, meta={"mode": mode, "tools": tools, "llm_used": llm_used, "grounded": grounded})  # fmt: skip
        return CoachTurn(am.id, reply, mode, tools, advice, escalation_suggested, escalation_id, llm_used, grounded)

    async def send(self, user_id: uuid.UUID, conv_id: uuid.UUID, text: str, request_id: str | None = None) -> CoachTurn:
        conv = await self._conv(user_id, conv_id)
        await self._add(conv.id, "user", text)

        # 1. Governance guards run before routing and before any model sees the text.
        if indicates_distress(text):
            esc_id = await self._try_escalate(user_id, "distress", conv.id, request_id)
            return await self._finish(conv, user_id, DISTRESS_RESPONSE, "information", "other", ["guard:distress"],
                                      escalation_suggested=True, escalation_id=esc_id, request_id=request_id)  # fmt: skip
        if asks_for_regulated_advice(text):
            await audit(self.s, action="advice.regulated_request_declined", entity_type="conversation", entity_id=str(conv.id),
                        actor_user_id=user_id, request_id=request_id)  # fmt: skip
            return await self._finish(conv, user_id, SAFE_DECLINE, "information", "other", ["guard:regulated"],
                                      escalation_suggested=True, request_id=request_id)  # fmt: skip
        if HUMAN_REQUEST.search(text):
            esc_id = await self._try_escalate(user_id, "user_request", conv.id, request_id)
            return await self._finish(conv, user_id, HUMAN_REPLY, "information", "other", ["guard:human_request"],
                                      escalation_suggested=True, escalation_id=esc_id, request_id=request_id)  # fmt: skip

        # 2. Deterministic routing and tool execution (read-only, scoped to this user).
        r = route(text)
        if not r.tools:
            return await self._finish(conv, user_id, f"I can only help with your own numbers right now. {CAPABILITIES}", "information",
                                      "other", [], request_id=request_id)  # fmt: skip
        tools = CoachTools(self.s, self.cfg, user_id)
        results = [await self._run_tool(tools, name, text) for name in r.tools]
        facts = "\n".join(t.text for t in results)
        reply, llm_used, grounded, fallback, pv = facts, False, True, None, None

        # 3. Optional LLM rewrite of the facts. Rejected unless every number is grounded and the class is safe.
        if self.provider is not None:
            system, pv = get_prompt("coach_explain", "v1")
            try:
                out = (
                    await self.provider.complete(
                        system=system, messages=[LLMMessage("user", f"FACTS:\n{facts}\n\nQUESTION: {text}")], max_tokens=500
                    )
                ).text.strip()
            except LLMUnavailable:
                out, fallback = "", "llm_unavailable"
            if out:
                # Only numbers the engine produced (or echoed back as assumptions inside the facts) are allowed: a number planted in
                # the user's message must not become an AI-stated "fact" (prompt-injection defence).
                ok, _bad = numbers_grounded(out, numbers_in(facts))
                if not ok:
                    fallback = "ungrounded_number"
                elif classify_output(out) in {*BLOCKED_CLASSES, "recommendation"}:
                    fallback = "unsafe_class"
                elif len(out) > MAX_REPLY_CHARS:
                    fallback = "too_long"
                else:
                    reply, llm_used = out, True
            grounded = fallback is None

        advice = classify_output(reply)
        if advice in BLOCKED_CLASSES:  # perimeter not approved (D-B9)
            reply, advice = SAFE_DECLINE, "information"
        return await self._finish(conv, user_id, reply, advice, r.mode, [t.tool for t in results], llm_used=llm_used,
                                  prompt_version=pv, grounded=grounded, fallback=fallback, request_id=request_id)  # fmt: skip

    async def _try_escalate(
        self, user_id: uuid.UUID, reason: str, conv_id: uuid.UUID, request_id: str | None
    ) -> uuid.UUID | None:
        try:
            return (await create_escalation(self.s, user_id, reason, None, conv_id, request_id)).id
        except AppError:  # e.g. too many open requests: still show the support text
            return None
